import {chromium, expect} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
const url=process.argv[2], out='docs/validation/sqlite-current';
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(); await page.goto(url); await page.waitForSelector('.vs-js');
const checks=[];
await page.getByRole('button',{name:'Next',exact:true}).click();
await expect(page.locator('.vs-step-status')).toContainText('1 of 2');
checks.push({check:'walkthrough advances and dims other parts',dimmed:await page.locator('#x-read_paths .vs-dim').count()});
await page.screenshot({path:`${out}/walkthrough-1440.png`});
await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.locator('#x-read_paths .vs-viewport [data-vs-target="read_wal"]').first().click();
await expect(page.locator('.vs-inspector')).toBeVisible();
await expect(page.locator('.vs-inspector')).toContainText('newest version within');
checks.push({check:'edge opens explanatory inspector',geometry:await page.locator('#x-read_paths .vs-viewport').evaluate(e=>({client:e.clientWidth,scroll:e.scrollWidth}))});
await page.screenshot({path:`${out}/inspector-1440.png`});
await page.getByRole('button',{name:'Close',exact:true}).click();
await expect(page.locator('.vs-inspector')).toBeHidden();
await page.locator('#x-check_repeat summary').click();
await expect(page.locator('#x-check_repeat')).toContainText('A still reads 100');
checks.push({check:'self-check answer opens',passed:true});
await page.setViewportSize({width:390,height:1000});
await page.getByRole('button',{name:'Show map: One commit leaves two valid answers',exact:true}).click();
await page.locator('#x-two_answers').scrollIntoViewIfNeeded();
checks.push({check:'mobile alternate trace map',geometry:await page.locator('#x-two_answers .vs-viewport').evaluate(e=>({client:e.clientWidth,scroll:e.scrollWidth}))});
await page.screenshot({path:`${out}/trace-map-390.png`});
await page.locator('#x-two_answers .vs-viewport [data-vs-target="a_old"]').first().click();
await expect(page.locator('dialog.vs-inspector')).toBeVisible();
await expect(page.locator('dialog.vs-inspector')).toContainText('without ending its transaction');
await page.screenshot({path:`${out}/inspector-390.png`});
await page.getByRole('button',{name:'Close',exact:true}).click();
checks.push({check:'mobile diagram detail opens and closes',passed:true});
await writeFile(`${out}/interaction-results.json`,JSON.stringify(checks,null,2));
console.log(JSON.stringify(checks,null,2));
await context.close(); await browser.close();
